import json

def write_dict(path, name, data):
    with open(path, 'w', encoding='utf-8') as f:
        f.write('/** Traduções (chave = texto em português). */\n')
        f.write(f'export const {name}: Record<string, string> = ')
        f.write(json.dumps(data, ensure_ascii=False, indent=2))
        f.write(';\n')

write_dict('src/i18n/en.ts', 'EN', EN)
